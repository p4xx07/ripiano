import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import path from "node:path";

const username = process.env.RIPIANO_E2E_USERNAME;
const password = process.env.RIPIANO_E2E_PASSWORD;
const fixture = path.resolve(process.cwd(), "e2e/fixtures/judge.png");

test("review invalid values, convert a custom detail, and search it as a number", async ({ page }, testInfo) => {
  test.skip(!username || !password, "Set RIPIANO_E2E_USERNAME and RIPIANO_E2E_PASSWORD");
  await page.goto("/");
  await page.getByLabel("Username").fill(username!);
  await page.getByLabel("Password").fill(password!);
  await page.getByRole("button", { name: "Sign in" }).click();
  await expect(page.getByRole("heading", { name: /Everything in its place/ })).toBeVisible();
  const stamp = `${Date.now().toString(36).slice(-6)}-${testInfo.project.name}`;
  const name = `type-change-${stamp}`;
  const field = `Amount ${stamp}`;
  const add = page.getByRole("button", { name: "Add document", exact: true });
  if (await add.isVisible()) await add.click();
  else await page.getByRole("button", { name: "Add", exact: true }).click();
  const chooser = page.waitForEvent("filechooser");
  await page.getByRole("button", { name: /Browse files/ }).click();
  await (await chooser).setFiles({ name: `${name}.png`, mimeType: "image/png", buffer: readFileSync(fixture) });
  await page.getByRole("button", { name, exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Keep it in place." });
  const custom = dialog.locator(".custom-fields");
  await custom.getByText("Add a custom field").click();
  await custom.getByRole("textbox", { name: "Field name" }).fill(field);
  await custom.getByRole("button", { name: "Add field" }).click();
  const row = custom.locator(".custom-field-row").filter({ hasText: field });
  await row.getByRole("textbox", { name: field }).fill("not-a-number");
  await row.getByRole("button", { name: "Save" }).click();
  const manage = dialog.locator(".custom-manage");
  await manage.locator("summary").click();
  await manage.getByRole("button", { name: `Change type of ${field}` }).click();
  await expect(manage.getByRole("combobox", { name: `New type for ${field}` })).toHaveValue("number");
  await manage.getByRole("button", { name: "Review change" }).click();
  let confirmation = page.getByRole("dialog", { name: `Change ${field} to Number?` });
  await expect(confirmation).toContainText("1 value cannot become number");
  await expect(confirmation.getByRole("button", { name: "Confirm type change" })).toBeDisabled();
  await page.screenshot({ path: testInfo.outputPath("type-change-blocked.png"), animations: "disabled" });
  await confirmation.getByRole("button", { name: "Cancel" }).click();
  await row.getByRole("textbox", { name: field }).fill("001.20");
  await row.getByRole("button", { name: "Save" }).click();
  await manage.getByRole("button", { name: "Review change" }).click();
  confirmation = page.getByRole("dialog", { name: `Change ${field} to Number?` });
  await expect(confirmation).toContainText("001.20 → 1.2");
  await confirmation.getByRole("button", { name: "Confirm type change" }).click();
  await expect(row.getByRole("spinbutton", { name: field })).toHaveValue("1.2");
  await page.screenshot({ path: testInfo.outputPath("type-change-complete.png"), animations: "disabled" });
  await dialog.getByRole("button", { name: "Close" }).click();
  await page.getByRole("textbox", { name: "Search documents" }).fill(`field:"${field}=1.2"`);
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
});
