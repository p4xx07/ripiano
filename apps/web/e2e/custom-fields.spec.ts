import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import path from "node:path";

const username = process.env.RIPIANO_E2E_USERNAME;
const password = process.env.RIPIANO_E2E_PASSWORD;
const fixture = path.resolve(process.cwd(), "e2e/fixtures/judge.png");

test("create a typed detail, find it by value, and clear it", async ({ page }, testInfo) => {
  test.skip(!username || !password, "Set RIPIANO_E2E_USERNAME and RIPIANO_E2E_PASSWORD");
  await page.goto("/");
  await page.getByLabel("Username").fill(username!);
  await page.getByLabel("Password").fill(password!);
  await page.getByRole("button", { name: "Sign in" }).click();
  await expect(page.getByRole("heading", { name: /Everything in its place/ })).toBeVisible();
  const stamp = `${Date.now()}-${testInfo.project.name}`;
  const name = `policy-${stamp}`;
  const field = `Policy number ${stamp}`;
  const reference = `PN-${stamp}`;
  const add = page.getByRole("button", { name: "Add document", exact: true });
  if (await add.isVisible()) await add.click();
  else await page.getByRole("button", { name: "Add", exact: true }).click();
  const chooser = page.waitForEvent("filechooser");
  await page.getByRole("button", { name: /Browse files/ }).click();
  await (await chooser).setFiles({ name: `${name}.png`, mimeType: "image/png", buffer: readFileSync(fixture) });
  await page.getByRole("button", { name, exact: true }).click();
  let dialog = page.getByRole("dialog", { name: "Keep it in place." });
  const custom = dialog.locator(".custom-fields");
  await custom.getByText("Add a custom field").click();
  await custom.getByRole("textbox", { name: "Field name" }).fill(field);
  await custom.getByRole("button", { name: "Add field" }).click();
  const row = custom.locator(".custom-field-row").filter({ hasText: field });
  await row.getByRole("textbox", { name: field }).fill(reference);
  await row.getByRole("button", { name: "Save" }).click();
  await expect(custom.getByRole("status")).toContainText(`${field} saved.`);
  await custom.screenshot({ path: testInfo.outputPath("custom-field.png") });
  await dialog.getByRole("button", { name: "Close" }).click();

  await page.getByRole("textbox", { name: "Search documents" }).fill(reference);
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  await expect(page.locator(".document-row").filter({ has: page.getByRole("button", { name, exact: true }) }).locator(".document-snippet")).toContainText(`Custom field: ${field}: ${reference}`);
  await page.getByRole("textbox", { name: "Search documents" }).fill(`field:"${field}=${reference}"`);
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  const result = page.locator(".document-row").filter({ has: page.getByRole("button", { name, exact: true }) });
  await expect(result.locator(".document-snippet")).toContainText(`Custom field: ${field}: ${reference}`);
  await page.getByRole("textbox", { name: "Search documents" }).fill("");
  await page.getByRole("button", { name: /^Filters/ }).click();
  await page.getByLabel("Custom detail").selectOption({ label: field });
  await page.getByLabel(`${field} value`).fill(reference);
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  await page.locator("#library-filters").screenshot({ path: testInfo.outputPath("custom-filter.png") });
  const savedName = `Policy filter ${stamp}`;
  await page.getByRole("button", { name: "Save this search" }).click();
  await page.getByRole("textbox", { name: "Saved search name" }).fill(savedName);
  await page.getByRole("button", { name: "Save search" }).click();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.getByRole("button", { name: savedName, exact: true }).click();
  await expect(page.getByLabel("Custom detail")).toHaveValue((await (await page.request.get("/api/custom-fields")).json()).fields.find((item: { name: string }) => item.name === field).id);
  await expect(page.getByLabel(`${field} value`)).toHaveValue(reference);
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  await page.getByRole("button", { name, exact: true }).click();
  dialog = page.getByRole("dialog", { name: "Keep it in place." });
  const reopened = dialog.locator(".custom-fields .custom-field-row").filter({ hasText: field });
  await expect(reopened.getByRole("textbox", { name: field })).toHaveValue(reference);
  await reopened.getByRole("button", { name: "Clear" }).click();
  await expect(dialog.locator(".custom-fields").getByRole("status")).toContainText(`${field} cleared.`);
  await dialog.getByRole("button", { name: "Close" }).click();
  await expect(page.getByRole("heading", { name: "Nothing found yet" })).toBeVisible();
  page.once("dialog", (confirmation) => void confirmation.accept());
  await page.getByRole("button", { name: `Delete saved search ${savedName}` }).click();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.getByRole("button", { name, exact: true }).click();
  dialog = page.getByRole("dialog", { name: "Keep it in place." });
  const manage = dialog.locator(".custom-manage");
  await manage.locator("summary").click();
  await manage.getByRole("button", { name: `Rename ${field}` }).click();
  const renamed = `${field} updated`;
  await manage.getByRole("textbox", { name: `New name for ${field}` }).fill(renamed);
  await manage.getByRole("button", { name: "Save name" }).click();
  await expect(manage).toContainText(renamed);
  page.once("dialog", (confirmation) => void confirmation.accept());
  await manage.getByRole("button", { name: `Delete unused field ${renamed}` }).click();
  await expect(dialog.locator(".custom-fields").getByRole("status")).toContainText(`Deleted unused field “${renamed}”.`);
  const premiumField = `Premium ${stamp}`;
  await custom.getByText("Add a custom field").click();
  await custom.getByRole("textbox", { name: "Field name" }).fill(premiumField);
  await custom.getByRole("combobox", { name: "Type", exact: true }).selectOption("number");
  await custom.getByRole("button", { name: "Add field" }).click();
  const premiumRow = custom.locator(".custom-field-row").filter({ hasText: premiumField });
  await premiumRow.getByRole("spinbutton", { name: premiumField }).fill("125.5");
  await premiumRow.getByRole("button", { name: "Save" }).click();
  await expect(custom.getByRole("status")).toContainText(`${premiumField} saved.`);
  await dialog.getByRole("button", { name: "Close" }).click();
  await page.getByLabel("Custom detail").selectOption({ label: premiumField });
  await page.getByRole("spinbutton", { name: `${premiumField} from` }).fill("100");
  await page.getByRole("spinbutton", { name: `${premiumField} to` }).fill("130");
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  await page.locator("#library-filters").screenshot({ path: testInfo.outputPath("custom-range.png") });
  const rangeName = `Premium range ${stamp}`;
  await page.getByRole("button", { name: "Save this search" }).click();
  await page.getByRole("textbox", { name: "Saved search name" }).fill(rangeName);
  await page.getByRole("button", { name: "Save search" }).click();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.getByRole("button", { name: rangeName, exact: true }).click();
  await expect(page.getByRole("spinbutton", { name: `${premiumField} from` })).toHaveValue("100");
  await expect(page.getByRole("spinbutton", { name: `${premiumField} to` })).toHaveValue("130");
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
});
