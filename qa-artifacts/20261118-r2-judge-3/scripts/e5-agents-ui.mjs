import { start, OUT } from "./pw.mjs";
import { BASE } from "./api.mjs";
const { browser, page, errors } = await start();
page.on("dialog", d => { console.log("DIALOG", d.message()); d.accept(); });
await page.getByRole("button", { name: "Agents", exact: true }).click();
await page.getByRole("textbox", { name: "Name" }).fill("j3r2-ui-cloud2");
await page.getByRole("checkbox", { name: "Read OCR text" }).check();
await page.getByRole("combobox", { name: "Document access" }).selectOption({ label: "Only “j3r2-agentA” documents" });
await page.getByRole("spinbutton", { name: /Expires after/ }).fill("2");
const resp = page.waitForResponse(r => r.url().endsWith("/api/agents") && r.request().method() === "POST");
await page.getByRole("button", { name: /Create|Connect|Add/ }).last().click();
const token = (await (await resp).json()).token;
await page.waitForTimeout(600);
const s = await page.locator("main").ariaSnapshot();
console.log(s.split("\n").slice(0, 30).join("\n").replaceAll(token, "rpa_***MASKED***"));
const tokenLoc = page.getByText(token, { exact: false });
await page.screenshot({ path: OUT + "02-agent-created-token-masked.png", mask: [tokenLoc, page.locator("input[readonly], code, pre")], fullPage: false });
const mcp = async () => (await fetch(BASE + "/mcp", { method: "POST", headers: { Authorization: "Bearer " + token, "Content-Type": "application/json", Accept: "application/json, text/event-stream" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list" }) }));
const r1 = await mcp(); console.log("before revoke", r1.status, (await r1.json()).result?.tools?.map(t => t.name));
await page.getByRole("button", { name: "Revoke j3r2-ui-cloud2" }).click();
await page.waitForTimeout(800);
const confirm = page.locator(".agent-revoke-confirm");
console.log("CONFIRM:", (await confirm.innerText()).replace(/\n/g," | "), "focused:", await page.evaluate(() => document.activeElement?.textContent));
await page.locator("article", { hasText: "j3r2-ui-cloud2" }).first().screenshot({ path: OUT + "03-agent-revoke-confirm.png" });
await confirm.getByRole("button").first().click(); await page.waitForTimeout(1000);
const r2 = await mcp(); console.log("after revoke", r2.status);
await page.locator("article", { hasText: "j3r2-ui-cloud2" }).first().screenshot({ path: OUT + "04-agent-revoked-card.png" });
console.log("ERRORS", errors);
await browser.close();
